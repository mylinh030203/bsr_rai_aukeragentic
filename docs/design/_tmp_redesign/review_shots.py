import pathlib, re
from playwright.sync_api import sync_playwright
URL = "file:///D:/ReasonaryAI/BSR_Market_Intel%20-%20auker/docs/design/prototype/index.html"
OUT = pathlib.Path("docs/design/_tmp_redesign/shots"); OUT.mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 1440, "height": 900})
    pg.goto(URL)
    pg.get_by_role("button", name=re.compile("Ban lãnh đạo")).first.click()
    pg.wait_for_selector(".market-tape-track", timeout=20000)
    pg.wait_for_timeout(1200)
    pg.screenshot(path=str(OUT / "rv-overview-light-1440.png"))
    pg.locator(".metric-card").first.click()
    pg.wait_for_timeout(600)
    pg.screenshot(path=str(OUT / "rv-inline-light-1440.png"))
    pg.locator('[data-theme-value="dark"]').click()
    pg.wait_for_timeout(500)
    pg.screenshot(path=str(OUT / "rv-inline-dark-1440.png"))
    pg.locator('[data-action="close-inline-metric"]').click()
    pg.wait_for_timeout(400)
    pg.screenshot(path=str(OUT / "rv-overview-dark-1440.png"))
    pg.goto(URL + "#market-data")
    pg.wait_for_timeout(900)
    pg.screenshot(path=str(OUT / "rv-marketdata-dark-1440.png"))
    pg.set_viewport_size({"width": 390, "height": 844})
    pg.goto(URL + "#overview")
    pg.wait_for_timeout(900)
    pg.evaluate("window.scrollTo(0,0)")
    pg.wait_for_timeout(300)
    pg.screenshot(path=str(OUT / "rv-overview-dark-390.png"))
    b.close()
print("done")
